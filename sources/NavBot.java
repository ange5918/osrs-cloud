    private static long key(int x,int y,int p){ return ((long)x<<24)|((long)y<<2)|p; }

    private boolean blocked(int x,int y,int p){
        if(x<X0||x>X1||y<Y0||y>Y1||p<0||p>=PL) return true;
        int idx=(p*NY+(y-Y0))*NX+(x-X0);
        return ((bits[idx>>3]>>(idx&7))&1)!=0;
    }
    private boolean diagOk(int x,int y,int p,int dx,int dy){
        return !blocked(x+dx,y,p) && !blocked(x,y+dy,p);
    }

    /** 官方同款 A*，返回从 start 到 goal 的路径（含跨层边）。 */
    private List<Pt> astar(int sx,int sy,int sp,int gx,int gy,int gp){
        PriorityQueue<Pt> open=new PriorityQueue<>(new Comparator<Pt>(){
            public int compare(Pt a,Pt b){ return Double.compare(a.g+h(a), b.g+h(b)); }
            private double h(Pt t){ return Math.max(Math.abs(t.x-gx),Math.abs(t.y-gy))+Math.abs(t.p-gp)*5; }
        });
        Map<Long,Double> best=new HashMap<>();
        Map<Long,Pt> parent=new HashMap<>();
        Map<Long,Edge> pedge=new HashMap<>();
        Pt s=new Pt(sx,sy,sp); s.g=0; open.add(s); best.put(key(sx,sy,sp),0.0);
        int iter=0;
        while(!open.isEmpty() && iter++<300000){
            Pt c=open.poll();
            if(c.x==gx&&c.y==gy&&c.p==gp){
                LinkedList<Pt> out=new LinkedList<>(); Pt cur=c;
                while(cur!=null){ out.addFirst(cur); cur=parent.get(key(cur.x,cur.y,cur.p)); }
                return out;
            }
            double cg=best.getOrDefault(key(c.x,c.y,c.p),1e18);
            if(c.g>cg) continue;
            // 8方向
            for(int[] d:STEPS){
                int nx=c.x+d[0], ny=c.y+d[1];
                if(blocked(nx,ny,c.p)) continue;
                if(d[0]!=0&&d[1]!=0&&!diagOk(c.x,c.y,c.p,d[0],d[1])) continue;
                double ng=cg+((d[0]!=0&&d[1]!=0)?1.4142:1.0);
                long nk=key(nx,ny,c.p);
                if(ng<best.getOrDefault(nk,1e18)){
                    best.put(nk,ng); Pt np=new Pt(nx,ny,c.p); np.g=ng;
                    parent.put(nk,c); pedge.put(nk,null); open.add(np);
                }
            }
            // transports 跨层边
            List<Edge> es=edgeIdx.get(key(c.x,c.y,c.p));
            if(es!=null) for(Edge e:es){
                double ng=cg+1.0;
                long nk=key(e.dx,e.dy,e.dp);
                if(ng<best.getOrDefault(nk,1e18)){
                    best.put(nk,ng); Pt np=new Pt(e.dx,e.dy,e.dp); np.g=ng;
                    parent.put(nk,c); pedge.put(nk,e); open.add(np);
                }
            }
        }
        return Collections.emptyList();
    }

    @Subscribe
    public void onTick(GameTick tick){
        if(finished||!client.isLoggedIn()) return;
        WorldPoint me=client.getLocalPlayerLocation();
        if(me==null) return;
        long t=client.getTickCount();
        if(legStartTick<0) legStartTick=t;

        // 到达目标?
        if(me.getX()==goalX&&me.getY()==goalY&&me.getPlane()==goalP
           || Math.abs(me.getX()-goalX)<=2&&Math.abs(me.getY()-goalY)<=2&&me.getPlane()==goalP){
            if(!reachedL2){
                ctx.log("[实时导航] ★★★到达 L2 "+me+" → 规划 GE2");
                reachedL2=true; setGoal(3203,3473,2,"GE2");
                return;
            } else {
                ctx.log("[实时导航] ★★★★到达终点 GE2 "+me+" 全部完成！");
                finished=true; return;
            }
        }

        // 需要重新规划：无路径 / 走完 / 卡住（不定时重规划，避免打断行走）
        boolean needReplan = path.isEmpty() || pathIdx>=path.size() || stuckTicks>100;
        if(needReplan){
            List<Pt> p=astar(me.getX(),me.getY(),me.getPlane(),goalX,goalY,goalP);
            if(p.isEmpty()){
                if(t-lastLogTick>=100){ lastLogTick=t;
                    ctx.log("[实时导航] 规划失败 "+me+" -> "+goalName); }
                return;
            }
            path=p; pathIdx=0; lastReplanTick=t; stuckTicks=0;
            ctx.log("[实时导航] 规划 "+p.size()+"步 "+me.getX()+","+me.getY()+",p"+me.getPlane()
                    +" -> "+goalName);
        }

        // 心跳
        if(lastLogTick<0||t-lastLogTick>=60){
            lastLogTick=t;
            ctx.log("[实时导航] pos="+me.getX()+","+me.getY()+",p"+me.getPlane()
                    +" 步"+pathIdx+"/"+path.size()+" ->"+goalName);
        }

        // 卡住检测
        if(me.getX()==lastX&&me.getY()==lastY) stuckTicks++; else stuckTicks=0;
        lastX=me.getX(); lastY=me.getY();

        if(pathIdx>=path.size()) return;
        Pt target=path.get(pathIdx);

        // 跨层边（plane 变化）-> 发楼梯包（先走到楼梯格附近）
        if(target.p!=me.getPlane()){
            int pd=Math.max(Math.abs(target.x-me.getX()),Math.abs(target.y-me.getY()));
            if(pd>2){
                if(lastWalkTick<0||t-lastWalkTick>=8){ client.walkTo(target.x,target.y); lastWalkTick=t; }
                return;
            }
            if(lastInteractTick<0||t-lastInteractTick>=40){
                lastInteractTick=t; interactTries++;
                Pt prev=pathIdx>0?path.get(pathIdx-1):me2pt(me);
                Edge ed=findEdge(prev.x,prev.y,prev.p,target.x,target.y,target.p);
                int oid=ed!=null?ed.oid:guessOid(prev.p,target.p);
                sendStair(oid,prev.x,prev.y,target.p>prev.p);
                ctx.log("[实时导航] ↑楼梯 obj="+oid+" p"+prev.p+"->p"+target.p
                        +" @"+(prev.x)+","+(prev.y)+" try"+interactTries);
            }
            return;
        }
        interactTries=0;

        // 推进 pathIdx：路径上已被走过的点（当前位置附近）
        while(pathIdx<path.size()){
            Pt q=path.get(pathIdx);
            int qd=Math.max(Math.abs(q.x-me.getX()),Math.abs(q.y-me.getY()));
            if(qd<=2 && q.p==me.getPlane()) pathIdx++; else break;
        }
        if(pathIdx>=path.size()) return;

        // ★远点行走：沿路径取前方第 10 格(同plane)作 walk 目标,让客户端自己寻路
        Pt far=path.get(pathIdx);
        for(int i=pathIdx+1;i<path.size() && i<pathIdx+14;i++){
            Pt q=path.get(i);
            if(q.p!=me.getPlane()) break;          // 遇到跨层就停在这段末尾
            far=q;
        }
        int fdx=far.x-me.getX(), fdy=far.y-me.getY();
        int fdist=Math.max(Math.abs(fdx),Math.abs(fdy));
        if(fdist<2 && pathIdx+1<path.size()){
            // 已很接近远点,推进
            pathIdx++; lastWalkTick=-1; return;
        }
        if(lastWalkTick<0||t-lastWalkTick>=10){
            client.walkTo(far.x,far.y);
            lastWalkTick=t;
        }
    }

    private Pt me2pt(WorldPoint me){ return new Pt(me.getX(),me.getY(),me.getPlane()); }

    private Edge findEdge(int sx,int sy,int sp,int dx,int dy,int dp){
        List<Edge> es=edgeIdx.get(key(sx,sy,sp));
        if(es==null) return null;
        for(Edge e:es) if(e.dx==dx&&e.dy==dy&&e.dp==dp) return e;
        return null;
    }
    private int guessOid(int fromP,int toP){
        // Lumbridge 城堡楼梯 / GE 楼梯兜底
        if(toP>fromP) return fromP==0?16671:(fromP==1?16672:11807);
        return fromP==1?16673:16672;
    }

    /** Ghost rev242 楼梯发包：op1=88/9字节; 多动作楼梯用旧格式103/8字节带opt */
    private void sendStair(int oid,int x,int y,boolean up){
        int lo=oid&0xff, hi=(oid>>8)&0xff, b2=(oid>>16)&0xff;
        int X=x&0xffff, Y=y&0xffff;
        int xX=(X&0xff)^0x80, hiX=(X>>8)&0xff;
        int hiY=(Y>>8)&0xff, loY=Y&0xff, xY=(Y&0xff)^0x80;
        if(oid==16672){ // 多动作楼梯
            int opt=up?1:2;
            client.sendPacket(103,new byte[]{(byte)hiX,(byte)xX,(byte)hiY,(byte)xY,
                (byte)(lo^0x80),(byte)hi,(byte)opt,(byte)0x80});
        } else {
            client.sendPacket(88,new byte[]{(byte)xX,(byte)hiX,(byte)hiY,(byte)loY,0,
                (byte)lo,(byte)hi,(byte)b2,0});
        }
    }
